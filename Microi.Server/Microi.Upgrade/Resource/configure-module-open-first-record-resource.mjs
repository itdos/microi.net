import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const resourceDir = path.dirname(fileURLToPath(import.meta.url));
const syncBase = process.argv.includes('--sync-base');
const modulePaths = [path.join(resourceDir, 'app.microi.module-engine.json')];
const saasPaths = [path.join(resourceDir, 'app.microi.saas-engine.json')];
if (syncBase) {
  modulePaths.push(path.join(resourceDir, '.resource-sync-base', 'app.microi.module-engine.json'));
  saasPaths.push(path.join(resourceDir, '.resource-sync-base', 'app.microi.saas-engine.json'));
}

const SYS_MENU_TABLE_ID = '1d28e502-70ea-4a2b-9793-699b3f42234e';
const OPEN_FIRST_RECORD_FIELD_ID = '01M0GC4Q6G7P3JZ8YABKXE4R5T';
const CROSS_DEVICE_TAB_ID = '8b6677d2-164c-4e34-a6fb-30eb7f10d1ef';
const SYSTEM_CONFIG_MENU_ID = 'ea6b79e8-2c6b-4d0f-9b6a-44d01a3479bf';

function versionParts(value) {
  return String(value || '').replace(/^v/i, '').split('.').map((part) => Number(part) || 0);
}

function maxVersion(current, target) {
  const left = versionParts(current);
  const right = versionParts(target);
  const length = Math.max(left.length, right.length);
  for (let index = 0; index < length; index += 1) {
    const l = left[index] || 0;
    const r = right[index] || 0;
    if (l > r) return current;
    if (l < r) return target;
  }
  return current || target;
}

function prependHistory(info, line) {
  const existing = String(info.ChangeHistory || '');
  if (!existing.includes(line)) info.ChangeHistory = existing ? `${line}\n${existing}` : line;
}

function addCapability(info, capability) {
  const capabilities = Array.isArray(info.RequiredPlatformCapabilities)
    ? info.RequiredPlatformCapabilities
    : [];
  if (!capabilities.includes(capability)) capabilities.push(capability);
  info.RequiredPlatformCapabilities = capabilities;
}

function configureModulePackage(filePath) {
  const packageData = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const info = packageData.PackageInfo || (packageData.PackageInfo = {});
  info.Version = maxVersion(info.Version, 'v7.5.1');
  info.Description = '模块引擎基础资源。记录直达由 sys_menu.OpenFirstRecord 控制，表单分组与工作台外观统一读取 diy_table 物理属性。';
  prependHistory(info, '2026-08-21 v7.5.1 将“进入模块默认打开第一条记录”迁移为 sys_menu.OpenFirstRecord 物理字段；模块设置与表单设置各归其所属引擎，旧 ViewSchema 配置继续兼容读取。');
  addCapability(info, 'ServerField:SysMenu.OpenFirstRecord');

  const table = (packageData.DiyTables || []).find((item) =>
    String(item.Name || '').toLowerCase() === 'sys_menu');
  if (!table) throw new Error(`${filePath}: sys_menu diy_table missing`);

  const field = {
    Id: OPEN_FIRST_RECORD_FIELD_ID,
    TableId: table.Id || SYS_MENU_TABLE_ID,
    Name: 'OpenFirstRecord',
    Label: '进入模块默认打开第一条记录',
    Description: '开启后直接进入统一表单工作台并自动选择第一条记录；切换记录仅更新当前模块 URL。弹窗、抽屉和子表中的记录切换不改宿主路由。',
    Type: 'int',
    Component: 'Switch',
    DefaultValue: '0',
    Sort: 6405,
    TableWidth: '160',
    FormWidth: 24,
    Visible: 1,
    AppVisible: 1,
    Readonly: 0,
    NotEmpty: 0,
    NameConfirm: 1,
    IsDeleted: 0,
    Tab: CROSS_DEVICE_TAB_ID,
  };
  const fields = packageData.DiyFields || (packageData.DiyFields = []);
  const fieldIndex = fields.findIndex((item) =>
    String(item.TableId || '') === String(table.Id || SYS_MENU_TABLE_ID)
      && String(item.Name || '').toLowerCase() === 'openfirstrecord');
  if (fieldIndex >= 0) fields[fieldIndex] = { ...fields[fieldIndex], ...field, Id: fields[fieldIndex].Id || field.Id };
  else fields.push(field);

  const columns = packageData.PhysicalColumns || (packageData.PhysicalColumns = []);
  const column = {
    TABLE_NAME: 'sys_menu',
    COLUMN_NAME: 'OpenFirstRecord',
    COLUMN_TYPE: 'int(11)',
    DATA_TYPE: 'int',
    IS_NULLABLE: 'YES',
    COLUMN_DEFAULT: '0',
    COLUMN_COMMENT: '进入模块默认打开第一条记录',
    COLUMN_KEY: '',
    EXTRA: '',
    ORDINAL_POSITION: Math.max(0, ...columns
      .filter((item) => String(item.TABLE_NAME || '').toLowerCase() === 'sys_menu')
      .map((item) => Number(item.ORDINAL_POSITION) || 0)) + 1,
  };
  const columnIndex = columns.findIndex((item) =>
    String(item.TABLE_NAME || '').toLowerCase() === 'sys_menu'
      && String(item.COLUMN_NAME || '').toLowerCase() === 'openfirstrecord');
  if (columnIndex >= 0) columns[columnIndex] = { ...columns[columnIndex], ...column };
  else columns.push(column);

  const ddl = (packageData.DDLStatements || []).find((item) =>
    String(item.TableName || '').toLowerCase() === 'sys_menu');
  if (!ddl) throw new Error(`${filePath}: sys_menu DDL missing`);
  if (!/`OpenFirstRecord`/i.test(ddl.DDL || '')) {
    ddl.DDL = String(ddl.DDL).replace(
      /\n\) ENGINE=/i,
      ",\n  `OpenFirstRecord` int NULL DEFAULT 0 COMMENT '进入模块默认打开第一条记录'\n) ENGINE=",
    );
  } else {
    // Repair resources generated by the first implementation, which appended
    // the new column without separating it from the preceding column.
    ddl.DDL = String(ddl.DDL).replace(
      /([^\s,])(\r?\n\s*`OpenFirstRecord`\s+int)/i,
      '$1,$2',
    );
  }

  info.FieldCount = fields.length;
  info.PhysicalColumnCount = columns.length;
  fs.writeFileSync(filePath, `${JSON.stringify(packageData, null, 2)}\n`, 'utf8');
}

function configureSaasPackage(filePath) {
  const packageData = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const info = packageData.PackageInfo || (packageData.PackageInfo = {});
  info.Version = maxVersion(info.Version, 'v7.5.7');
  prependHistory(info, '2026-08-21 v7.5.7 系统设置菜单改由 sys_menu.OpenFirstRecord 默认直达首条记录；从 diy_table.FormPresentation 兼容 JSON 移除模块级开关。');
  addCapability(info, 'ServerField:SysMenu.OpenFirstRecord');

  const menu = (packageData.SysMenus || []).find((item) => String(item.Id || '') === SYSTEM_CONFIG_MENU_ID);
  if (!menu) throw new Error(`${filePath}: system-config sys_menu missing`);
  menu.OpenFirstRecord = 1;

  const table = (packageData.DiyTables || []).find((item) =>
    String(item.Name || '').toLowerCase() === 'sys_config');
  if (table && table.FormPresentation) {
    try {
      const legacyPresentation = JSON.parse(table.FormPresentation);
      table.FormPresentationMode = legacyPresentation.Presentation || 'ControlCenter';
      table.FormPresentationDensity = legacyPresentation.Density || 'Compact';
      table.FormNavigationTitle = legacyPresentation.NavigationTitle || '表单分组';
      table.FormNavigationCountText = legacyPresentation.NavigationCountText || '{count} 项';
      table.FormSectionNavigation = legacyPresentation.SectionNavigation || 'Auto';
      table.FormSectionEyebrow = legacyPresentation.SectionEyebrow || 'FORM SECTION';
      table.FormRequiredCountText = legacyPresentation.RequiredCountText || '{count} 必填项';
      table.FormWorkbenchEyebrow = legacyPresentation.WorkbenchEyebrow || 'FORM WORKBENCH';
      table.FormWorkbenchDescription = legacyPresentation.WorkbenchDescription || '';
      table.FormNavigationFooterTitle = legacyPresentation.NavigationFooterTitle || '';
      table.FormNavigationFooterHtml = legacyPresentation.NavigationFooterHtml || '';
      const selector = legacyPresentation.RecordSelector || {};
      table.FormRecordSelectorPlaceholder = selector.Placeholder || '搜索并切换系统配置';
      table.FormRecordSelectorLabelFields = JSON.stringify(selector.LabelFields || []);
      delete legacyPresentation.OpenFirstRecord;
      table.FormPresentation = JSON.stringify(legacyPresentation);
    } catch (error) {
      throw new Error(`${filePath}: sys_config.FormPresentation is invalid JSON: ${error.message}`);
    }
  }

  fs.writeFileSync(filePath, `${JSON.stringify(packageData, null, 2)}\n`, 'utf8');
}

for (const filePath of modulePaths) configureModulePackage(filePath);
for (const filePath of saasPaths) configureSaasPackage(filePath);

console.log('Configured sys_menu.OpenFirstRecord in module and SaaS resources.');
