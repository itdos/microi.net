import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';

const pkg = JSON.parse(await readFile(new URL('./app.microi.saas-engine.json', import.meta.url), 'utf8'));
const table = pkg.DiyTables.find(item => item.Name === 'sys_osclients');
const fieldName = 'TcpIngressRulesJson';
const portFieldName = 'TcpIngressPort';
const enableFieldName = 'TcpIngressEnable';

test('SaaS 包只交付 TCP 入站配置结构，空规则不监听且不覆盖租户值', () => {
  assert.ok(table);
  const fields = pkg.DiyFields.filter(item => item.TableId === table.Id && item.Name === fieldName);
  assert.equal(fields.length, 1);
  const field = fields[0];
  assert.equal(field.Type, 'mediumtext');
  assert.equal(field.Component, 'CodeEditor');
  assert.equal(field.FormWidth, 24);
  assert.equal(field.AppVisible, 0);
  assert.equal(JSON.parse(field.Config).CodeEditor.Language, 'json');
  assert.equal(Object.hasOwn(field, 'DefaultValue'), false);
  const tabs = JSON.parse(table.Tabs);
  assert.ok(tabs.some(item => item.Id === field.Tab && item.Name === '后端运行配置'));

  const columns = pkg.PhysicalColumns.filter(item => item.TABLE_NAME === table.Name && item.COLUMN_NAME === fieldName);
  assert.equal(columns.length, 1);
  assert.equal(columns[0].COLUMN_TYPE, 'mediumtext');
  assert.equal(columns[0].IS_NULLABLE, 'YES');
  assert.equal(columns[0].COLUMN_DEFAULT, null);
  const createTable = pkg.DDLStatements.find(item => item.TableName === table.Name && !item.IndexName);
  assert.match(createTable.DDL, /`TcpIngressRulesJson` mediumtext NULL/u);
  const portFields = pkg.DiyFields.filter(item => item.TableId === table.Id && item.Name === portFieldName);
  assert.equal(portFields.length, 1);
  assert.equal(portFields[0].Type, 'int');
  assert.equal(portFields[0].Component, 'NumberText');
  assert.equal(portFields[0].Tab, field.Tab);
  assert.equal(portFields[0].AppVisible, 0);
  assert.equal(Object.hasOwn(portFields[0], 'DefaultValue'), false);
  assert.match(portFields[0].Description, /1885/u);
  const portColumns = pkg.PhysicalColumns.filter(item => item.TABLE_NAME === table.Name && item.COLUMN_NAME === portFieldName);
  assert.equal(portColumns.length, 1);
  assert.equal(portColumns[0].DATA_TYPE, 'int');
  assert.equal(portColumns[0].IS_NULLABLE, 'YES');
  assert.equal(portColumns[0].COLUMN_DEFAULT, null);
  assert.match(createTable.DDL, /`TcpIngressPort` int NULL/u);
  const enableFields = pkg.DiyFields.filter(item => item.TableId === table.Id && item.Name === enableFieldName);
  assert.equal(enableFields.length, 1);
  assert.equal(enableFields[0].Type, 'int');
  assert.equal(enableFields[0].Component, 'Switch');
  assert.equal(JSON.parse(enableFields[0].Config).Switch.NullValue, 1);
  assert.equal(enableFields[0].Tab, field.Tab);
  assert.equal(enableFields[0].AppVisible, 0);
  assert.equal(Object.hasOwn(enableFields[0], 'DefaultValue'), false);
  assert.match(enableFields[0].Description, /空值或 1.*0/u);
  const enableColumns = pkg.PhysicalColumns.filter(item => item.TABLE_NAME === table.Name && item.COLUMN_NAME === enableFieldName);
  assert.equal(enableColumns.length, 1);
  assert.equal(enableColumns[0].DATA_TYPE, 'int');
  assert.equal(enableColumns[0].IS_NULLABLE, 'YES');
  assert.equal(enableColumns[0].COLUMN_DEFAULT, null);
  assert.match(createTable.DDL, /`TcpIngressEnable` int NULL/u);
  const mqttEnableFields = pkg.DiyFields.filter(item => item.TableId === table.Id && item.Name === 'MqttEnable');
  assert.equal(mqttEnableFields.length, 1);
  assert.equal(mqttEnableFields[0].Component, 'Switch');
  assert.equal(JSON.parse(mqttEnableFields[0].Config).Switch.NullValue, 1);
  assert.equal(pkg.DataSets.some(item => JSON.stringify(item).includes(fieldName)), false);
  assert.equal(pkg.DataSets.some(item => JSON.stringify(item).includes(portFieldName)), false);
  assert.equal(pkg.DataSets.some(item => JSON.stringify(item).includes(enableFieldName)), false);
  assert.equal(pkg.PackageInfo.FieldCount, pkg.DiyFields.length);
  assert.equal(pkg.PackageInfo.PhysicalColumnCount, pkg.PhysicalColumns.length);
  assert.equal(pkg.PackageInfo.ChangeLog.Version, pkg.PackageInfo.Version);
});
