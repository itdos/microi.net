import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeOfficialPackageExecutionLimits } from './resource-sync-core.mjs';

const directory = path.dirname(fileURLToPath(import.meta.url));
const packagePath = path.join(directory, 'app.microi.saas-engine.json');
const sourcePath = path.resolve(directory, '../../../Microi-V8-Engine/Microi吾码 (api.itdos.com)/iTdos.Product.Internal/接口引擎/系统/[SaaS引擎]一键制作主库空数据库(admin_build_sanitized_empty_database).js');
const source = fs.readFileSync(sourcePath, 'utf8').replace(/\r\n?/g, '\n').replace(/\n*$/, '\n');
const pkg = JSON.parse(fs.readFileSync(packagePath, 'utf8'));
const version = 'v8.2.2';
const releaseTime = '2026-09-07 03:38:00';
const title = '空数据库发布租约等待与恢复';
const content = '服务重启后，后台任务租约与数据库发布租约可能先后到期；空库制作在确认尚未修改临时库的占用状态下延迟续跑，保留检查点并等待原发布释放，不再把短暂租约占用报成失败。继续保留经官方包校验的安装版本基线。';
if (pkg.PackageInfo.Name !== 'SaaS引擎' || !['v8.2.1', version].includes(pkg.PackageInfo.Version)) throw Error('Unexpected SaaS package identity/version');
const key = 'admin_build_sanitized_empty_database';
const engine = pkg.SysApiEngines.find(x => x.ApiEngineKey === key);
if (!engine || !['v1.0.9', 'v1.0.10'].includes(engine.Version)) throw Error('Unexpected empty database worker version');
if (pkg.ResourcePolicies.ApiEngines[key]?.UpgradePolicy !== 'Managed') throw Error('Worker must remain Managed');
if (!source.includes('Version: v1.0.10') || !source.includes('EMPTY_DATABASE_RELEASE_LEASE_WAIT_V1')) throw Error('Canonical worker source is not updated');
const prependOnce = (old, line) => String(old || '').split(/\r?\n/).includes(line) ? old : line + '\n' + String(old || '');
engine.ApiV8Code = source;
engine.Version = 'v1.0.10';
engine.UpdateTime = releaseTime;
engine.ChangeHistory = prependOnce(engine.ChangeHistory, releaseTime + ' v1.0.10 空库发布租约占用时安全延迟续跑');
pkg.PackageInfo.Version = version;
pkg.PackageInfo.ChangeHistory = prependOnce(pkg.PackageInfo.ChangeHistory, '2026-09-07 ' + version + ' ' + content);
pkg.PackageInfo.ChangeLog = { Version: version, Title: title, ChangeType: 'Fix', Content: content, ReleaseTime: releaseTime };
fs.writeFileSync(packagePath, normalizeOfficialPackageExecutionLimits(path.basename(packagePath), JSON.stringify(pkg, null, 2)).replace(/\n*$/, '\n'));
console.log(version + ' v1.0.10');
