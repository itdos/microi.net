const previewBySlide = new Map(trainingPreviewAssets.map(asset => [`${asset.edition}:${asset.theme}:${asset.index}`, asset.url]))

export function trainingPreviewPath(edition, index, isDark) {
  if (!['technical', 'enterprise'].includes(edition) || !Number.isSafeInteger(index) || index < 0) return ''
  return previewBySlide.get(`${edition}:${isDark ? 'dark' : 'light'}:${index + 1}`) || ''
}
